    private void tProductListMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tProductListMouseClicked
        // TODO add your handling code here:
        int count = -1;
        selectedRecord = tProductList.getSelectedRow();
        
        //The id of the select record
        String selectionID = tProductList.getModel().getValueAt(tProductList.getSelectedRow(), 0).toString();
        
        //Read the line in file and get the actual row line in the file
        try (BufferedReader reader = new BufferedReader(new FileReader("product\\product.txt"))) {
            String line;
            while ((line = reader.readLine()) != null) {
                String[] lineArray = line.split(",");
                    count = count + 1;
                if (selectionID.equals(lineArray[0])) {
                    break;
                }
            }
        //Replaced selectedRecord to actual row line    
        selectedRecord = count;
        } catch (Exception e) {
            e.getMessage();
        }
        
    }//GEN-LAST:event_tProductListMouseClicked

