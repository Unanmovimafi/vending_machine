    private void bMoveUpActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bMoveUpActionPerformed
        // TODO add your handling code here:
        String line;
        List<String> lines = new ArrayList<>();
        
        try (
            BufferedReader reader = new BufferedReader(new FileReader("product\\product.txt"))
        ){  //Read and add all the lines in file to line
            while ((line = reader.readLine()) != null) {
                lines.add(line);
            }
        reader.close();
        } catch (Exception e) {
            e.getMessage();
        }
        
        if (selectedRecord > 0) {
            //swap the line
            Collections.swap(lines, selectedRecord, selectedRecord - 1);
            try (BufferedWriter writer = new BufferedWriter(new FileWriter("product\\product.txt"))) {
                for (String updatedLine : lines) {
                    //rewrite the whole line to file.
                    writer.write(updatedLine);
                    writer.newLine();
                }
            writer.close();
            } catch (Exception e) {
                e.getMessage();
            }
        } else {
            //If user choose the top product
            JOptionPane.showMessageDialog(null, "This item is already at the top");
        }
    refreshTable("");
    selectedRecord =selectedRecord - 1;
    }//GEN-LAST:event_bMoveUpActionPerformed

    private void bMoveDownActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bMoveDownActionPerformed
        // TODO add your handling code here:
        String line;
        List<String> lines = new ArrayList<>();
        
        try (BufferedReader reader = new BufferedReader(new FileReader("product\\product.txt"))) {
            while ((line = reader.readLine()) != null) {
                ////Read and add all the lines in file to line
                lines.add(line);
            }
        reader.close();
        } catch (Exception e) {
            e.getMessage();
        }
        if (selectedRecord < lines.size() - 1) {
            //swap the line
            Collections.swap(lines, selectedRecord, selectedRecord + 1);
            try (BufferedWriter writer = new BufferedWriter(new FileWriter("product\\product.txt"))) {
                for (String updatedLine : lines) {
                    //rewrite the whole line to file.
                    writer.write(updatedLine);
                    writer.newLine();
                }
            } catch (Exception e) {
                e.getMessage();
            }
        } else {
            //If user choose the bottom product
            JOptionPane.showMessageDialog(null, "This item is already at the bottom");
        }
    refreshTable("");
    selectedRecord =selectedRecord + 1;
    }//GEN-LAST:event_bMoveDownActionPerformed

