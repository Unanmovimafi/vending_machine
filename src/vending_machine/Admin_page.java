    private void bDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bDeleteActionPerformed
        // TODO add your handling code here:
        List<String> lines = fp.getAllProductRecord();
        
        int currentIndex = -1;
        
        if (selectedRecord != -1) {
            String[] record = fp.getProductRecord(selectedRecord);
            lines.set(selectedRecord, "");
            //Show up dialog to confirm delete
            int option=JOptionPane.showConfirmDialog(null,"Do you want to remove this item from your cart?","Remove Item",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.QUESTION_MESSAGE);
            if(option==JOptionPane.YES_OPTION){
                //Delete the record
                try {
                    BufferedWriter writer = new BufferedWriter(new FileWriter("product\\product.txt"));
                    for (String updatedLine : lines) {
                        currentIndex++;
                        //skip the speific record
                        if (currentIndex == selectedRecord) {
                            continue;
                        }
                        else {
                        //rewrite other line to file
                        writer.write(updatedLine);
                        writer.newLine();
                        }
                    }
                    writer.close();
                    }
                
                 catch (Exception e) {
                    e.getMessage();
                }
                //delete the old image
                File oldFile = new File ("product\\image\\" + record[5]);
                oldFile.delete();
                
                //Show message dialog to present the record has been delete
                JOptionPane.showMessageDialog(null, "Successfully Deleted!");
            }
        }
        else{
            //If no product was selected, pop up to notify user to choose product
            JOptionPane.showMessageDialog(null, "Please select a product to delete!");
            }
        refreshTable("");
    }//GEN-LAST:event_bDeleteActionPerformed

