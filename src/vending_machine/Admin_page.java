    public void refreshTable(String nameOfProduct) {
        DefaultTableModel model = (DefaultTableModel)tProductList.getModel();
        model.setRowCount(0);
        String line;
        
        try {
            BufferedReader br = new BufferedReader(new FileReader("product\\product.txt"));
            while ((line = br.readLine()) != null) {
                String[] record = line.split(",");
                if (record[1].toLowerCase().startsWith(nameOfProduct)) {
                    //Get the location of image
                    String imageLocation = "product\\image\\" +record[5];
                    //Set the image properties
                    ImageIcon imageIcon = new ImageIcon(imageLocation);
                    Image setIcon = imageIcon.getImage().getScaledInstance(60, 60, Image.SCALE_SMOOTH);
                    ImageIcon img = new ImageIcon(setIcon);

                    //Add the record to Table
                    model.addRow(record);

                    int rowIndex = model.getRowCount() - 1;
                    int columnIndex = model.getColumnCount() - 2;
                    //set Image to the Table
                    tProductList.setValueAt(img, rowIndex, columnIndex);
                    }
                }
            br.close();
        } catch (Exception e) {
            e.getMessage();
        }
    }
    
    private void createDatetimeUpdater() {
        // Every one second trigger the updateDatetime
        Timer timer = new Timer(1000, new ActionListener() {
            @Override
            public void actionPerformed(ActionEvent e) {
                updateDatetime();
            }
        });
        timer.start();
    }
    
    private void updateDatetime() {
        SimpleDateFormat sdf = new SimpleDateFormat("dd/MM/yyyy HH:mm:ss");
        String datetime = sdf.format(new Date());
        lDateTime.setText(datetime);
    }
    
    
