    private void bAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bAddActionPerformed
        // TODO add your handling code here:
        //Check if any field is empty
        if (tfName.getText().isEmpty() ||cbCategory.getSelectedItem().equals("Please Select") || tfPrice.getText().isEmpty()|| tfStock.getText().isEmpty()|| tfImageLocation.getText().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please enter all fields.");
        }
        
        else {
            //Get the value from each text field
            String name = tfName.getText();
            String category = (String) cbCategory.getSelectedItem();
            String price = tfPrice.getText();
            String stock = tfStock.getText();
            StringBuilder product = new StringBuilder();
            
            //Check if price is numeric
            try{
                Double.parseDouble(price);
            }

            catch (Exception e)
                    {JOptionPane.showMessageDialog(null, "Please only insert numeric value in price.");
                    return;}
            
            //Check if stock is integer
            try{
                Integer.parseInt(stock);
            }

            catch (Exception e)
                    {JOptionPane.showMessageDialog(null, "Please only integer number in stock.");
                    return;}


             try {
                 
                //Write the information to the text file
                product.append(totalLine +","+name+"," + category + "," +price + "," +stock + "," + desFileName + ",Active");

                BufferedWriter writer = new BufferedWriter(new FileWriter("product\\product.txt", true));
                writer.write(product + "\n");
                writer.close();


            try {
                //Copy the image file to folder
                Files.copy(sourceFile.toPath(), destinationFile.toPath());

            } catch (Exception e) {
                e.getMessage();
            }



                } 
             catch (Exception e) {
                System.err.println(e.getMessage());
            }

            JOptionPane.showMessageDialog(null, "Successfully Added!");
            this.dispose();
            adminPageInstance.refreshTable("");
        }
        
        
        
    }//GEN-LAST:event_bAddActionPerformed

    private void bChooseImageActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bChooseImageActionPerformed
        // TODO add your handling code here:
        JFileChooser chooser = new JFileChooser();
        chooser.showOpenDialog(null);
        File file=chooser.getSelectedFile();
        if (file != null){
        ImageIcon imageIcon = new ImageIcon(file.toString());
        Image setIcon = imageIcon.getImage().getScaledInstance(150,150, Image.SCALE_SMOOTH);
        ImageIcon img = new ImageIcon(setIcon);
        lImage.setIcon(img);
        
        String filePath = file.getAbsolutePath();
        tfImageLocation.setText(filePath);
        
        
        String path = "product/image";
        
        sourceFile = new File(filePath);
        
        String extension = filePath.substring(filePath.lastIndexOf(".")+1);
        
        
        destinationFile = new File (path+ "/product"+ totalLine+ "." + extension);
        desFileName = ("product"+ totalLine+ "." + extension);}
        
    }//GEN-LAST:event_bChooseImageActionPerformed

