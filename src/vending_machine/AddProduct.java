    private void getId(){
        int maximumNumber = 0;
        String line;
        try {
            BufferedReader bufferedReader = new BufferedReader(new FileReader("product\\product.txt"));

            while ((line = bufferedReader.readLine()) != null) {
                String[] lineArray = line.split(",");
                int currentNumber = Integer.parseInt(lineArray[0]);
                if (currentNumber > maximumNumber) {
                    //Get the maximum id in text file
                    maximumNumber = currentNumber;
                }
            }
            //The maximum number plus one to be the id
            maximumNumber = maximumNumber +1;
            bufferedReader.close();
            totalLine = Integer.toString(maximumNumber);
        } catch (Exception e) {
            System.err.println(e.getMessage());
        }
    }

